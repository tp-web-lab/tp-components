import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
const browser=await chromium.launch();
try {
 const page=await browser.newPage({viewport:{width:1200,height:900}});
 await page.goto(`${process.env.TP_VIEWER_TEST_URL ?? 'http://127.0.0.1:4197'}/docs/components/component-viewer/demo.html`);
 await page.locator('[data-component-mode] input').nth(1).check();
 await page.locator('[data-component-source-toggle]').click();
 const source=page.locator('[data-component-source]');
 assert.deepEqual(await source.locator('[role=tab]').allTextContents(),['HTML','tp-asciidoc','tp-latex','tp-markdown','tp-restructuredtext']);
 await source.getByRole('tab',{name:'tp-latex',exact:true}).click();
 const editor=source.locator('[data-component-source-format=latex]');
 await editor.locator('.cm-editor').waitFor();
 assert.match(await editor.evaluate(el=>el.value),/(?:\\wcTpButton|tp-button)/);
 assert.equal(await editor.getAttribute('readonly'),'');
 const frame=page.frameLocator('iframe');
 await frame.locator('tp-button').waitFor();
 const initial=(await page.locator('iframe').boundingBox()).height;
 await frame.locator('body').evaluate(body=>{const e=document.createElement('div');e.id='late-content';e.style.height='500px';body.append(e);});
 await page.waitForFunction(h=>document.querySelector('iframe').getBoundingClientRect().height>h+450,initial);
 await frame.locator('#late-content').evaluate(el=>el.remove());
 await page.waitForFunction(h=>document.querySelector('iframe').getBoundingClientRect().height<h+30,initial);
 const before=(await editor.boundingBox()).height;
 await page.locator('[data-component-content]').evaluate(el=>{el.value=Array.from({length:30},(_,i)=>`<p>Line ${i}: ${'Word '.repeat(25)}</p>`).join('\n');el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.waitForFunction(h=>document.querySelector('[data-component-source-format=latex]').getBoundingClientRect().height>h+200,before);
 const grown=(await editor.boundingBox()).height;
 await page.setViewportSize({width:420,height:900});
 await page.waitForTimeout(250);
 assert.ok((await editor.boundingBox()).height>=grown);
 await source.getByRole('tab',{name:'HTML',exact:true}).click();
 await source.getByRole('tab',{name:'tp-latex',exact:true}).click();
 assert.ok((await editor.boundingBox()).height>before);
 await page.locator('[data-component-content]').evaluate(el=>{el.value='Short';el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.waitForFunction(h=>document.querySelector('[data-component-source-format=latex]').getBoundingClientRect().height<h+100,before);
 assert.match(await editor.evaluate(el=>el.value),/Short/);
 await page.locator('tp-component-viewer').evaluate(el=>el.setAttribute('tag','tp-word-cloud'));
 await page.waitForTimeout(300);
 await page.locator('[data-component-mode] input').nth(1).check();
 await page.locator('[data-component-source-toggle]').click();
 await source.getByRole('tab',{name:'tp-latex',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-component-source-format=latex]')?.value.includes('\\wcTpWordCloud'));
 assert.match(await editor.evaluate(el=>el.value),/\\wcTpIcon/);
 console.log('Passed: five named tabs, readonly LaTeX, live content, two component types, iframe growth/shrink, editor growth/shrink, tab switching and narrow width.');
} finally {await browser.close();}
