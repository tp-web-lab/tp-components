/** Grouped mask controls stay outside the target in one document. */
import { writeFileSync } from 'node:fs';
export function maskAttributesExample(directory) {
 const settings = [{name:'active',value:false},{name:'anchor',value:''}];
 const script = `// Generated by scripts/mask-attribute-example.mjs.\nconst settings = ${JSON.stringify(settings)};
await Promise.all(['tp-mask','tp-textfield','tp-checkbox-list','tp-button'].map(tag=>customElements.whenDefined(tag)));
const active=document.querySelector('#mask-active');
const anchor=document.querySelector('#mask-anchor');
const area=document.querySelector('#mask-preview');
let preview=area.querySelector('tp-mask');
const apply=()=>{preview.anchor=anchor.value;preview.active=active.value==='1';};
active.addEventListener('tp-checkbox-list-change',apply);
anchor.addEventListener('input',apply);
document.querySelector('#mask-reset').addEventListener('click',()=>{
 active.value=settings[0].value?'1':'';anchor.value=settings[1].value;apply();
});
document.querySelector('#mask-reload').addEventListener('click',()=>{
 preview.remove();area.replaceChildren();
 const field=document.createElement('tp-textfield');field.id='mask-answer';field.setAttribute('label','Answer');field.setAttribute('value','Thursday');field.setAttribute('clearable','');
 preview=document.createElement('tp-mask');preview.textContent='The answer is hidden until the review.';
 area.append(field,preview);apply();
});
`;
 writeFileSync(`${directory}/attributes.js`,script);
 return `<p>Enter <code>#mask-answer</code> in anchor, then enable active. Edit the answer before masking it and check that the value returns when active is unchecked. Clear anchor or use Reset defaults to restore the inactive defaults. Reload preview recreates the target with its initial value.</p>
<tp-stack>
<tp-checkbox-list id="mask-active" label="Boolean attributes" label-position="top" orientation="horizontal"><ul><li>active</li></ul></tp-checkbox-list>
<tp-textfield id="mask-anchor" label="anchor" label-position="top" placeholder="" clearable></tp-textfield>
<tp-button-group><tp-button id="mask-reset">Reset defaults</tp-button><tp-button id="mask-reload">Reload preview</tp-button></tp-button-group>
</tp-stack>
<tp-divider></tp-divider>
<tp-stack id="mask-preview">
<tp-textfield id="mask-answer" label="Answer" value="Thursday" clearable></tp-textfield>
<tp-mask>The answer is hidden until the review.</tp-mask>
</tp-stack>
<script type="module" src="/docs/components/mask/examples/attributes.js"></script>`;
}
