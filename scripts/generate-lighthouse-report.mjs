import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const reportDirectory = path.resolve('.lighthouseci/reports');
const outputPath = path.resolve('public/docs/appendices/lighthouse/index.md');
const manifest = JSON.parse(await readFile(path.join(reportDirectory, 'manifest.json'), 'utf8'));
const representativeRuns = manifest.filter((entry) => entry.isRepresentativeRun);

function pageLabel(url) {
  const parsed = new URL(url);
  if (parsed.hash !== '') return parsed.hash.replace(/^#\//, '');
  if (parsed.pathname === '/') return 'Cover';
  return parsed.pathname.replace(/^\//, '');
}

function percent(score) {
  return score === null || score === undefined ? 'n/a' : `${Math.round(score * 100)}%`;
}

const hostingAudits = new Set([
  'cache-insight',
  'network-dependency-tree-insight',
  'redirects',
  'server-response-time',
  'uses-http2',
  'uses-long-cache-ttl',
  'uses-text-compression',
]);

function findingOwner(id, audit) {
  if (hostingAudits.has(id)) return 'Hosting';
  const details = JSON.stringify(audit.details ?? {});
  if (/\/(?:chunks\/lib|node_modules)\/|cdn\.jsdelivr\.net|unpkg\.com/i.test(details)) {
    return 'Libraries';
  }
  return '`tp-*`';
}

const runs = await Promise.all(representativeRuns.map(async (entry) => {
  const jsonPath = path.isAbsolute(entry.jsonPath)
    ? entry.jsonPath
    : path.resolve(reportDirectory, entry.jsonPath);
  return {
    requestedUrl: entry.url,
    result: JSON.parse(await readFile(jsonPath, 'utf8')),
  };
}));

const scoreRows = runs
  .sort((left, right) => pageLabel(left.requestedUrl).localeCompare(pageLabel(right.requestedUrl)))
  .map(({ requestedUrl, result }) => `| ${pageLabel(requestedUrl)} | ${percent(result.categories.performance?.score)} | ${percent(result.categories.accessibility?.score)} | ${percent(result.categories['best-practices']?.score)} | ${percent(result.categories.seo?.score)} |`);

const findings = [];
for (const { requestedUrl, result } of runs) {
  for (const [id, audit] of Object.entries(result.audits)) {
    if (audit.score === null || audit.score >= 1 || audit.scoreDisplayMode === 'notApplicable') continue;
    const categories = Object.values(result.categories)
      .filter((category) => category.auditRefs?.some((reference) => reference.id === id))
      .map((category) => category.title)
      .join(', ');
    if (categories === '') continue;
    findings.push({
      page: pageLabel(requestedUrl),
      category: categories,
      audit: audit.title,
      owner: findingOwner(id, audit),
    });
  }
}

const findingRows = findings
  .sort((left, right) => left.owner.localeCompare(right.owner) || left.audit.localeCompare(right.audit) || left.page.localeCompare(right.page))
  .map((finding) => `| ${finding.owner} | ${finding.category} | ${finding.audit.replaceAll('|', '\\|')} | ${finding.page} |`);

const generated = `# Lighthouse

This report is generated by [Lighthouse CI](https://github.com/GoogleChrome/lighthouse-ci). It audits three autonomous HTML fixtures that use only \`tp-markup-single-page\` to render the Accessibility, Code editor and Markup multi-pages documents. This isolates the single-page renderer from the documentation shell and its multi-page navigation. Local runs use one measurement for quick feedback; CI uses the median representative result from three measurements to reduce variability.

[Lighthouse](https://developer.chrome.com/docs/lighthouse/overview/) is an automated web-page auditing tool maintained by the Chrome team. It opens each page in Chromium under controlled conditions, observes its loading and rendered DOM, and produces diagnostic scores from 0 to 100. These are laboratory indicators: they are useful for finding regressions and prioritising work, but they do not reproduce every user's device, network or assistive technology.

The four tested categories mean:

- **Performance** measures loading and visual stability indicators such as First Contentful Paint, Largest Contentful Paint, Total Blocking Time, Speed Index and Cumulative Layout Shift. It also reports possible causes such as unused JavaScript, large payloads, excessive DOM size and long dependency chains.
- **Accessibility** performs automated checks on the rendered page, including names, roles, relationships, contrast and document structure. It complements the cross-browser axe and manual reviews; a score of 100 does not prove complete accessibility.
- **Best practices** detects browser-facing implementation risks such as console errors, deprecated APIs, insecure resources and unsafe or obsolete behaviours. Findings may originate in \`tp-*\`, a loaded library or the hosting configuration.
- **SEO** checks whether search engines can understand and index the document, including its title, meta description, crawler directives, status and link semantics. For hash-based navigation, the score does not guarantee that every dynamic route will be indexed independently.

The initial thresholds are advisory: 80% performance, 95% accessibility, 90% best practices, and 90% SEO. A warning identifies a regression candidate but does not fail the component-quality workflow.

## Category scores

| Page | Performance | Accessibility | Best practices | SEO |
| --- | ---: | ---: | ---: | ---: |
${scoreRows.join('\n')}

## Triage by responsibility

The ownership classification is diagnostic, not contractual. \`tp-*\` covers component code, rendering and loading decisions; **Libraries** identifies findings whose evidence names a third-party bundle or CDN; **Hosting** covers caching, compression, protocol, redirects and server response. A library finding can still require a \`tp-*\` change when the component loads that library too early.

| Responsibility | Category | Audit | Page |
| --- | --- | --- | --- |
${findingRows.length > 0 ? findingRows.join('\n') : '| — | — | No incomplete audit in the representative runs | — |'}

Run \`pnpm lighthouse\` to collect reports, apply advisory assertions and regenerate this page. Full HTML and JSON reports are written to \`.lighthouseci/reports\` and retained by CI as artifacts.
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
console.info(`Updated ${path.relative(process.cwd(), outputPath)}.`);
